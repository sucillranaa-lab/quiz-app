/**
 * Scans QuizData/ directory and generates QuizData/index.js
 * that imports all quiz data files and exports them as a unified array.
 *
 * Naming convention:
 *   quizdataIFIC1.js  →  "IFIC Practice Test 1"
 *   quizdataIFIC2.js  →  "IFIC Practice Test 2"
 *
 * Run: node scripts/generate-quiz-index.js
 * Auto-runs before every build via package.json scripts.
 */

const fs = require('fs');
const path = require('path');

const quizDir = path.join(__dirname, '..', 'QuizData');
const indexPath = path.join(quizDir, 'index.js');

// Read all .js files in QuizData/, excluding index.js and hidden files
const files = fs.readdirSync(quizDir)
  .filter(f => f.endsWith('.js') && f !== 'index.js' && !f.startsWith('.'))
  .sort();

if (files.length === 0) {
  console.warn('⚠ No quiz data files found in QuizData/');
  fs.writeFileSync(indexPath, `// Auto-generated file. No quiz data files found.\nexport const quizSources = [];\n`);
  return;
}

const imports = [];
const entries = [];

for (const file of files) {
  const filePath = path.join(quizDir, file);
  const content = fs.readFileSync(filePath, 'utf-8');

  // Extract the exported constant name (e.g., "quizData", "IFIC_Practice_Test2")
  // Skip the optional displayName export
  const exportMatch = content.match(/export\s+const\s+(?!displayName\b)(\w+)/);
  if (!exportMatch) {
    console.warn(`⚠ Skipping ${file}: no exported constant found`);
    continue;
  }

  const constName = exportMatch[1]; // e.g., "quizData" or "IFIC_Practice_Test2"

  // Check for optional displayName export
  const displayNameMatch = content.match(/export\s+const\s+displayName\s*=\s*['"]([^'"]+)['"]/);

  let displayName;
  if (displayNameMatch) {
    displayName = displayNameMatch[1];
  } else {
    // Derive test name from filename
    // quizdataIFIC1.js  →  strip "quizdata", split "IFIC1"  →  name:"IFIC", num:"1"  →  "IFIC Practice Test 1"
    const baseName = file.replace('.js', '').replace(/^quizdata/, '');
    const nameMatch = baseName.match(/^([A-Za-z_]+?)(\d*)$/);
    const topicName = nameMatch ? nameMatch[1].replace(/_/g, ' ') : baseName;
    const number = nameMatch && nameMatch[2] ? nameMatch[2] : '';

    // Split on uppercase boundaries to form readable words: "IFICNumerical" → "IFIC Numerical"
    const words = topicName
      .replace(/([A-Z])([a-z])/g, ' $1$2')
      .trim()
      .split(/\s+/)
      .join(' ');

    displayName = number ? `${words} Practice Test ${number}` : words;
  }

  imports.push(`import { ${constName} } from './${file}';`);
  entries.push(`  { name: '${displayName}', data: ${constName} }`);
}

const output = `// Auto-generated file. Do not edit manually.
// Generated by: node scripts/generate-quiz-index.js

${imports.join('\n')}

export const quizSources = [
${entries.join(',\n')}
];
`;

fs.writeFileSync(indexPath, output);
console.log(`✓ Generated QuizData/index.js with ${entries.length} source(s):`);
entries.forEach(e => console.log(`  - ${e.match(/name: '([^']+)'/)[1]}`));
